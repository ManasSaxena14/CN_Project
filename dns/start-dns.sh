#!/bin/bash
# ───────────────────────────────────────────────────────────
# start-dns.sh — Start dnsmasq (Primary or Backup DNS Server)
#
# Generates dnsmasq.conf dynamically from config.env.
# Works identically on:
#   - Mac 1 (Primary DNS: $MAC1_IP)
#   - Mac 4 (Backup DNS:  $BACKUP_DNS_IP / Ext A)
#
# Usage:
#   sudo ./dns/start-dns.sh                     # uses APP_TARGET_IP and DNS_TTL from config.env
#   sudo ./dns/start-dns.sh --target 10.81.95.70 # override target IP (e.g. for Ext B/E cutover)
#   sudo ./dns/start-dns.sh --ttl 10             # override TTL
#   sudo ./dns/start-dns.sh python               # start Python fallback server
# ───────────────────────────────────────────────────────────
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"

if [ ! -f "$PROJECT_DIR/config.env" ]; then
    echo "ERROR: config.env not found in $PROJECT_DIR"
    exit 1
fi

source "$PROJECT_DIR/config.env"

TARGET_IP="${APP_TARGET_IP:-$MAC2_IP}"
TTL="${DNS_TTL:-30}"
MODE="dnsmasq"

# Parse CLI arguments
while [[ $# -gt 0 ]]; do
    case "$1" in
        --target|-t)
            TARGET_IP="$2"
            shift 2
            ;;
        --ttl)
            TTL="$2"
            shift 2
            ;;
        python)
            MODE="python"
            shift
            ;;
        dnsmasq)
            MODE="dnsmasq"
            shift
            ;;
        --help|-h)
            echo "Usage: sudo $0 [options]"
            echo ""
            echo "Options:"
            echo "  --target, -t <IP>   Override APP_TARGET_IP (currently: $TARGET_IP)"
            echo "  --ttl <seconds>     Override DNS_TTL (currently: $TTL)"
            echo "  python              Run minimal Python DNS server instead of dnsmasq"
            echo "  --help, -h          Show this help message"
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            echo "Use --help for usage."
            exit 1
            ;;
    esac
done

# Detect current host IP to determine role
LOCAL_IP=$(ipconfig getifaddr en0 2>/dev/null || true)
ROLE="DNS Server"
if [ "$LOCAL_IP" = "$MAC1_IP" ]; then
    ROLE="PRIMARY DNS (Mac 1)"
elif [ "$LOCAL_IP" = "$BACKUP_DNS_IP" ] || [ "$LOCAL_IP" = "$MAC4_IP" ]; then
    ROLE="BACKUP DNS (Mac 4 / Ext A)"
fi

echo "============================================================"
echo "  TEAM 1 — $ROLE"
echo "============================================================"
echo "  Local IP    : ${LOCAL_IP:-unknown}"
echo "  Domain      : $PROJECT_DOMAIN"
echo "  Target IP   : $TARGET_IP"
echo "  Record TTL  : ${TTL}s"
echo "  Port        : ${DNS_PORT:-53} (UDP)"
echo "============================================================"

# Stop any process already bound to port 53
if lsof -ti :${DNS_PORT:-53} >/dev/null 2>&1; then
    echo "Port ${DNS_PORT:-53} is in use. Stopping existing process..."
    sudo lsof -ti :${DNS_PORT:-53} 2>/dev/null | xargs sudo kill -9 2>/dev/null || true
    sleep 1
fi

if [ "$MODE" = "python" ]; then
    echo ""
    echo "Starting Python DNS Server..."
    if [ ! -f "$HOME/cn-phase1/dns/dns_server.py" ]; then
        cd "$PROJECT_DIR" && ./setup.sh mac1
    fi
    exec sudo python3 "$HOME/cn-phase1/dns/dns_server.py"
fi

# Generate dnsmasq configuration dynamically
CONF_FILE="$SCRIPT_DIR/dnsmasq.conf"
cat > "$CONF_FILE" <<EOF
# ───────────────────────────────────────────────────────────
# dnsmasq.conf — Autogenerated by start-dns.sh
# Generated at: $(date)
# ───────────────────────────────────────────────────────────

# Listen on all interfaces, UDP port ${DNS_PORT:-53}
listen-address=0.0.0.0
port=${DNS_PORT:-53}

# Project Authoritative A-records pointing to target edge IP
address=/app.${PROJECT_DOMAIN}/${TARGET_IP}
address=/api.${PROJECT_DOMAIN}/${TARGET_IP}

# TTL for project records (Phase 2: ${TTL}s)
local-ttl=${TTL}

# Authoritative domain boundary: return NXDOMAIN for any unmapped *.test
local=/${PROJECT_DOMAIN}/
local=/test/

# Forward non-project queries (e.g. google.com) to upstream DNS
server=8.8.8.8
server=8.8.4.4

# Resolver behavior: do not read local /etc/resolv.conf or /etc/hosts
no-resolv
no-hosts

# Query logging to stdout for auditing and viva demonstration
log-queries
# Without this dnsmasq on macOS sends the log to syslog, where it is lost
log-facility=-

# Keep in foreground so query stream is visible
keep-in-foreground
EOF

echo "Generated config at: $CONF_FILE"
echo ""
echo "Records configured:"
echo "  app.$PROJECT_DOMAIN  -> $TARGET_IP (TTL: ${TTL}s)"
echo "  api.$PROJECT_DOMAIN  -> $TARGET_IP (TTL: ${TTL}s)"
echo "  *.test (unknown)     -> NXDOMAIN"
echo "  public names         -> Forwarded to 8.8.8.8, 8.8.4.4"
echo ""
echo "dnsmasq starting in foreground (Ctrl+C to stop)..."
echo "============================================================"

exec sudo dnsmasq --conf-file="$CONF_FILE"
