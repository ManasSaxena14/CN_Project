#!/bin/bash
# ───────────────────────────────────────────────────────────
# failure-demos.sh  — Two failure scenarios for the viva
# Run each demo, capture output, then RESTORE DNS.
# ───────────────────────────────────────────────────────────
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR/..")"
source "$PROJECT_DIR/config.env"

echo ""
echo "============================================"
echo " FAILURE DEMO (a): Wrong DNS Server"
echo "============================================"
echo ""
echo "EXPLANATION: The client is pointed to a DNS server that"
echo "doesn't know about team1.test, so name resolution fails."
echo "But the underlying IP network (Layer 3) is fine — ping works."
echo ""
echo "Commands to run on the client Mac:"
echo ""
echo "  # 1. Point DNS to a wrong server (e.g., 192.0.2.1 — a black-hole IP)"
echo "  sudo networksetup -setdnsservers Wi-Fi 192.0.2.1"
echo "  sudo dscacheutil -flushcache; sudo killall -HUP mDNSResponder"
echo ""
echo "  # 2. DNS lookup FAILS (name can't resolve)"
echo "  dig app.team1.test           # → ;; connection timed out"
echo "  curl https://app.team1.test  # → Could not resolve host"
echo ""
echo "  # 3. But direct IP ping WORKS (network is fine, just DNS is broken)"
echo "  ping -c 2 $MAC2_IP           # → ✓ replies OK"
echo ""
echo "  # This proves: DNS is Layer 7 (Application). IP routing (Layer 3) is independent."
echo ""
echo "  # 4. RESTORE"
echo "  sudo networksetup -setdnsservers Wi-Fi $MAC1_IP"
echo "  sudo dscacheutil -flushcache; sudo killall -HUP mDNSResponder"
echo ""

echo ""
echo "============================================"
echo " FAILURE DEMO (b): DNS Points to Wrong IP"
echo "============================================"
echo ""
echo "EXPLANATION: DNS resolves app.team1.test correctly (returns an IP),"
echo "but we made it return MAC3_IP (Backend A) instead of MAC2_IP (nginx)."
echo "Backend A isn't listening on port 443, so the TCP handshake fails → 'Connection refused'."
echo ""
echo "Commands to run on Mac 1 (the DNS server):"
echo ""
echo "  # 1. If using dnsmasq, temporarily edit dnsmasq.conf:"
echo "  #    Change:  address=/app.team1.test/$MAC2_IP"
echo "  #    To:      address=/app.team1.test/$MAC3_IP"
echo "  #    Then restart dnsmasq."
echo ""
echo "  #    If using Python dns_server.py, edit the RECORDS dict"
echo "  #    to map app.team1.test → $MAC3_IP, restart."
echo ""
echo "  # 2. On any client, flush cache and test:"
echo "  sudo dscacheutil -flushcache; sudo killall -HUP mDNSResponder"
echo ""
echo "  dig app.team1.test           # → returns $MAC3_IP  (DNS 'succeeds')"
echo "  curl https://app.team1.test  # → 'Connection refused' (port 443 not open on Mac 3)"
echo ""
echo "  # This proves: DNS only maps names→IPs (Layer 7)."
echo "  # The TCP connection (Layer 4) to port 443 still needs a listening service."
echo "  # DNS success ≠ service availability."
echo ""
echo "  # 3. RESTORE: change dnsmasq.conf back to $MAC2_IP, restart dnsmasq."
echo ""
