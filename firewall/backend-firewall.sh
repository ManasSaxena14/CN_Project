#!/bin/bash
# firewall/backend-firewall.sh
# =============================================================================
# Service isolation using macOS pf (Packet Filter) — Ext C
#
# USAGE
#   sudo ./firewall/backend-firewall.sh apply   # lock down backend port
#   sudo ./firewall/backend-firewall.sh remove  # restore original pf state
#   sudo ./firewall/backend-firewall.sh status  # show anchor rules + current state
#
# RULES (once applied)
#   • TCP to the backend port (3001 on Mac 3, 3002 on Mac 4) is allowed
#     ONLY from MAC2_IP (primary edge) and STANDBY_EDGE_IP (standby edge, Mac 3).
#   • All other hosts get a silent DROP on that port.
#   • lo0 (loopback) is explicitly skipped so the process itself can still
#     connect to 127.0.0.1:<port> for health-checks.
#   • No other traffic is touched — we write to a named pf anchor
#     (com.apple/team1-backend), not over /etc/pf.conf.
#
# HOW TO FIND YOUR BACKEND PORT
#   Auto-detected: compare this Mac's LAN IP against MAC3_IP / MAC4_IP
#   in config.env.  Pass an explicit port as the second argument to override:
#       sudo ./firewall/backend-firewall.sh apply 3002
#
# BACKUP / ROLLBACK
#   Before the first `apply` the current ruleset is written to
#   /etc/pf.anchors/team1-backend.bak  (overwritten only on the very first run).
#   `remove` removes the anchor and restores the state captured in that backup.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
source "$SCRIPT_DIR/config.env"

# --------------------------------------------------------------------------- #
# Configuration
# --------------------------------------------------------------------------- #
ANCHOR_NAME="team1-backend"
ANCHOR_FILE="/etc/pf.anchors/${ANCHOR_NAME}"
BACKUP_FILE="/etc/pf.anchors/${ANCHOR_NAME}.bak"
# macOS /etc/pf.conf only evaluates anchors under "com.apple/*". A top-level
# anchor would load fine but NEVER be evaluated, so we load ours inside it.
PF_ANCHOR="com.apple/${ANCHOR_NAME}"

# Detect which backend port belongs to this Mac
detect_backend_port() {
    local my_ip
    my_ip=$(ipconfig getifaddr \
        "$(networksetup -listallhardwareports \
            | awk '/Wi-Fi/{getline; print $2}')" 2>/dev/null || true)

    if [ -z "$my_ip" ]; then
        # Fallback: first non-loopback IPv4
        my_ip=$(ifconfig | awk '/inet /{print $2}' | grep -v 127.0.0.1 | head -1)
    fi

    if [ "$my_ip" = "$MAC3_IP" ]; then
        echo "$BACKEND_A_PORT"
    elif [ "$my_ip" = "$MAC4_IP" ]; then
        echo "$BACKEND_B_PORT"
    else
        # Unknown host — default to the A port and warn
        echo "WARNING: local IP '$my_ip' doesn't match MAC3_IP or MAC4_IP" >&2
        echo "         Defaulting to BACKEND_A_PORT=$BACKEND_A_PORT" >&2
        echo "$BACKEND_A_PORT"
    fi
}

# Allow an explicit port override as $2
if [ -n "${2:-}" ]; then
    BACKEND_PORT="$2"
else
    BACKEND_PORT=$(detect_backend_port)
fi

# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
check_root() {
    if [ "$EUID" -ne 0 ]; then
        echo "ERROR: this script must run as root (use sudo)."
        exit 1
    fi
}

write_anchor_rules() {
    # Allow loopback unconditionally (pf skips lo0 by default, but be explicit)
    # Allow MAC2_IP (primary edge) → backend port
    # Allow STANDBY_EDGE_IP (standby edge, Mac 3) → backend port
    # Block everything else to that port (quiet drop, no RST)
    cat > "$ANCHOR_FILE" << RULES
# team1-backend anchor — generated by backend-firewall.sh
# Allow loopback (lo0 is exempt by default, but explicit is clearer)
pass quick on lo0

# Allow the primary edge (Mac 2) to reach the backend port
pass in quick proto tcp \
    from $MAC2_IP to any port $BACKEND_PORT

# Allow the standby edge (Mac 3 / STANDBY_EDGE_IP) to reach the backend port
pass in quick proto tcp \
    from $STANDBY_EDGE_IP to any port $BACKEND_PORT

# Block everyone else on the backend port (drop = silent, no RST)
block drop in quick proto tcp to any port $BACKEND_PORT
RULES
    echo "Anchor rules written to $ANCHOR_FILE"
    echo "  Allowed sources  : $MAC2_IP (primary edge)"
    echo "                     $STANDBY_EDGE_IP (standby edge)"
    echo "  Protected port   : $BACKEND_PORT/tcp"
}

# --------------------------------------------------------------------------- #
# Sub-commands
# --------------------------------------------------------------------------- #
cmd_apply() {
    check_root

    # --- 1. Back up existing state (once only) ---
    if [ ! -f "$BACKUP_FILE" ]; then
        # Record whether pf was enabled + the current rules (for rollback/evidence)
        { pfctl -si 2>/dev/null | grep -i '^Status'; pfctl -sr 2>/dev/null; } > "$BACKUP_FILE" || true
        echo "Backed up existing pf state to $BACKUP_FILE"
    else
        echo "Backup already exists at $BACKUP_FILE — skipping overwrite"
    fi

    # --- 2. Write the anchor rule file ---
    write_anchor_rules

    # --- 3. Load the anchor into pf ---
    # Register our anchor in the main ruleset (safe: only adds an anchor ref)
    # then load our rules into it.
    pfctl -a "$PF_ANCHOR" -f "$ANCHOR_FILE" || { echo "ERROR: pf rejected the rules - firewall NOT applied"; exit 1; }

    # Ensure pf is enabled
    pfctl -e 2>/dev/null || true

    echo ""
    echo "======================================================="
    echo " Firewall APPLIED — backend port $BACKEND_PORT isolated"
    echo " Only $MAC2_IP and $STANDBY_EDGE_IP can reach it"
    echo "======================================================="
    echo ""
    echo "Verify with: sudo pfctl -a $PF_ANCHOR -sr"
    echo "Remove with: sudo ./firewall/backend-firewall.sh remove"
}

cmd_remove() {
    check_root

    # --- 1. Flush our anchor ---
    pfctl -a "$PF_ANCHOR" -F rules 2>/dev/null || true
    echo "Anchor '$PF_ANCHOR' flushed."

    # --- 2. Restore original ruleset from backup ---
    if [ -f "$BACKUP_FILE" ]; then
        # Our rules lived only in our anchor, so flushing it already restored the
        # original ruleset (we never touch the main ruleset). Only undo pf -e
        # if pf was disabled before we applied.
        if grep -qi '^Status: *Disabled' "$BACKUP_FILE"; then
            pfctl -d 2>/dev/null || true
            echo "pf was disabled before - disabled it again."
        fi
        echo "Original pf state restored."
        rm -f "$BACKUP_FILE"
    else
        echo "No backup file found — nothing to restore."
    fi

    # --- 3. Remove our anchor file ---
    rm -f "$ANCHOR_FILE"

    echo ""
    echo "======================================================="
    echo " Firewall REMOVED — all hosts can reach port $BACKEND_PORT again"
    echo "======================================================="
}

cmd_status() {
    echo "===== pf global status ====="
    pfctl -si 2>/dev/null | head -5 || echo "(pfctl not available without sudo)"

    echo ""
    echo "===== anchor: $PF_ANCHOR ====="
    pfctl -a "$PF_ANCHOR" -sr 2>/dev/null \
        || echo "(no rules in anchor — firewall is not applied)"

    echo ""
    echo "===== backend port $BACKEND_PORT connections ====="
    lsof -nP -iTCP:"$BACKEND_PORT" -sTCP:LISTEN 2>/dev/null \
        || echo "(nothing listening on $BACKEND_PORT)"
}

# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #
case "${1:-help}" in
    apply)  cmd_apply  ;;
    remove) cmd_remove ;;
    status) cmd_status ;;
    *)
        echo "Usage: sudo $0 apply | remove | status [port]"
        echo ""
        echo "  apply  [port]  - isolate backend port (auto-detected from IP, or pass port)"
        echo "  remove [port]  - restore original pf state"
        echo "  status [port]  - show anchor rules and listening sockets"
        exit 0
        ;;
esac
